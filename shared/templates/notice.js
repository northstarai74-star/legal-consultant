import { text, area, select, date, jurisdictionField } from './helpers.js';

export default {
  id: 'notice',
  name: 'Legal Notice / Demand Letter',
  category: 'Disputes',
  icon: 'Gavel',
  popular: true,
  minutes: 2,
  blurb: 'A formal notice demanding payment, performance or that a party stops a wrongful act.',
  keywords: ['legal notice', 'demand letter', 'notice', 'demand', 'cease and desist', 'recovery', 'unpaid', 'breach'],
  fields: [
    text('sender', 'Sender (your name / company)', { group: 'Parties', required: true, prefill: 'organization' }),
    text('senderAddress', 'Sender address', { group: 'Parties', prefill: 'address' }),
    text('recipient', 'Recipient', { group: 'Parties', required: true }),
    text('recipientAddress', 'Recipient address', { group: 'Parties' }),
    date('noticeDate', 'Date of notice', { group: 'Notice' }),
    text('reference', 'Reference number', { group: 'Notice', placeholder: 'LN/2026/014' }),
    select('delivery', 'Sent by', ['Registered post / courier', 'Email and registered post', 'Hand delivery'], { group: 'Notice' }),
    text('subject', 'Subject', { group: 'Notice', required: true, placeholder: 'Notice for recovery of unpaid invoices' }),
    area('facts', 'Facts of the matter (one point per line)', { group: 'Matter', required: true, rows: 5, placeholder: 'On 10 March 2026 you agreed to purchase…\nInvoice no. 114 for INR 2,40,000 fell due on 10 April 2026…\nDespite reminders on…, you have failed to pay.' }),
    area('demand', 'What you demand', { group: 'Matter', required: true, rows: 3, placeholder: 'Pay INR 2,40,000 with interest at 12% p.a. from the due date' }),
    text('deadline', 'Time to comply', { group: 'Matter', default: '15 days' }),
    area('consequences', 'Consequence of non-compliance (optional)', { group: 'Matter', rows: 2, placeholder: 'Initiate civil and criminal proceedings at your risk as to costs and consequences' }),
    jurisdictionField({ group: 'Matter', label: 'Jurisdiction / applicable law' }),
  ],
  title: () => 'LEGAL NOTICE',
  render: (v) => {
    const points = (v.$facts || '[Facts of the matter]').split(/\n+/).map((s) => s.trim()).filter(Boolean);
    return [
      '# LEGAL NOTICE',
      '',
      `**Date:** ${v.noticeDate}  `,
      `**Ref:** ${v.reference}  `,
      `**Sent by:** ${v.delivery}`,
      '',
      '**To,**  ',
      `**${v.recipient}**  `,
      `${v.recipientAddress}`,
      '',
      `**Subject: ${v.subject}**`,
      '',
      'Sir / Madam,',
      '',
      `Under instructions from and on behalf of my/our client, **${v.sender}**, of ${v.senderAddress} (“**my client**”), I/we hereby serve upon you the following notice:`,
      '',
      '## Facts',
      '',
      ...points.flatMap((p, i) => [`**${i + 1}.** ${p.replace(/([\\`*_~|<])/g, '\\$1')}`, '']),
      '## Demand',
      '',
      `**${points.length + 1}.** In view of the above, you are called upon to comply with the following within **${v.deadline}** of receipt of this notice: ${v.demand}.`,
      '',
      ...(v.$consequences
        ? [`**${points.length + 2}.** Failing compliance within the said period, my client has instructed me/us to take the following steps, entirely at your risk as to costs and consequences: ${v.consequences}.`, '']
        : [`**${points.length + 2}.** Failing compliance within the said period, my client shall be constrained to initiate appropriate legal proceedings against you, entirely at your risk as to costs and consequences.`, '']),
      `**${points.length + 3}.** This notice is issued without prejudice to all other rights and remedies available to my client under law and equity, all of which are expressly reserved. This notice is governed by the laws of ${v.jurisdiction}. A copy has been retained in my/our office for record.`,
      '',
      'Yours faithfully,',
      '',
      `${'\\_'.repeat(26)}  `,
      `**${v.sender}**  `,
      `${v.senderAddress}`,
      '',
    ].join('\n');
  },
  clauses: () => [],
};
